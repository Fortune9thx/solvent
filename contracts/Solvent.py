"""
SOLVENT -- a single-issuer coverage bond on GenLayer.

One issuer capitalises a pool; beneficiaries enroll discrete coverage units
against a policy frozen at deployment. When a unit holder files a bonded
claim, the coverage question -- did this incident breach the frozen policy,
under evidence each validator fetches for itself over HTTPS? -- is settled
by GenLayer consensus, never by the issuer or the claimant.

Outcomes are DISCRETE ONLY: FULL, HALF, NONE, INCONCLUSIVE. There is no
awarded percentage and no claimant-proposed share; the payout schedule is a
pure function of the decision (see solventlib.accounting).

Money invariant, asserted after every mutation:

    pool_balance >= live_units * unit_face

`claim()` is the one and only method that moves GEN out of the contract,
and it only ever pays credits the deterministic ledger already granted.

Studio Next / Studio Dev only (chain id 61997). State may reset.

This single file is what the network receives. Sibling package imports are
not supported by contract validation, so contracts/build_bundle.py inlines
contracts/solventlib/* between the marker lines below. Edit
contracts/solventlib/*.py or this file, then re-run the bundler -- never
hand-edit the generated bundle.
"""

