# Maximum adjudication attempts recorded before a stuck claim may be
# cancelled. Combined with the time window below (see cancel_stale_claim).
MAX_JUDGE_ATTEMPTS = 3

# A claim that can never reach a settled verdict must still release its bond.
# "Permissionlessly retriable" is not "guaranteed to converge": a genuinely
# ambiguous claim, or a validator-infrastructure problem, can make every
# adjudicate attempt fail. After this long, anyone may cancel the claim and
# the bond is returned exactly. (datetime.now() is deterministic inside a
# GenLayer transaction on this Depends pin; see docs/SECURITY.md.)
EXPIRY_WINDOW_SECONDS = 259200  # 72h


def _now_ts() -> int:
    return int(datetime.now(timezone.utc).timestamp())


def _sender() -> str:
    return str(gl.message.sender_address)


def _sender_hex() -> str:
    return Address(_sender()).as_hex.lower()


def _make_unit_id(n: int) -> str:
    return "SOL-U" + str(n).zfill(8)


def _make_claim_id(n: int) -> str:
    return "SOL-C" + str(n).zfill(8)


